/* Вспомогательные функции на ассемблере для abi_stack.c (System V x86-64, AT&T).
 * На C их не написать: компилятор сам следит за выравниванием стека, а нам нужно
 * и посмотреть на RSP "как есть", и нарочно нарушить правило ABI. */

    .text

/* uintptr_t rsp_at_entry(void)
 * Возвращает RSP сразу после входа в функцию, то есть когда на стеке лежит
 * только адрес возврата, положенный инструкцией call. По ABI RSP перед call
 * кратен 16, значит здесь должен получиться остаток 8. */
    .globl rsp_at_entry
rsp_at_entry:
    movq %rsp, %rax
    ret

/* void call_misaligned(void (*fn)(void))
 * Вызывает fn со стеком, сдвинутым на 8 байт относительно требований ABI.
 * На входе сюда RSP % 16 == 8 (адрес возврата уже лежит на стеке). Обычная
 * функция сначала сдвинула бы RSP ещё на 8 (как sub $8 в прологе
 * test_backtrace). Мы этого не делаем и сразу вызываем fn, поэтому перед call
 * RSP % 16 == 8 вместо 0, а fn получит на входе 0 вместо положенных 8. */
    .globl call_misaligned
call_misaligned:
    call *%rdi
    ret

    .section .note.GNU-stack,"",@progbits
