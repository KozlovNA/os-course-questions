/* Вызываемая сторона для convention.c. Вынесена в отдельный файл: если определить
 * sum8 рядом с call_with_8_args, gcc -O2 посчитает вызов сам и подставит 36. */

/* Как вызванная функция видит аргументы 7 и 8: на стеке над адресом возврата,
 * по адресам 16(%rbp) и 24(%rbp). run.sh компилирует её с -O0. */
long sum8(long a1, long a2, long a3, long a4, long a5, long a6, long a7, long a8) {
    return a1 + a2 + a3 + a4 + a5 + a6 + a7 + a8;
}
