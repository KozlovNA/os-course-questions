// Почему UB — это НЕ "неизвестное, но конкретное значение от железа".
// Компилятор рассуждает от посылки "UB не бывает" и стирает целые ветки кода.
#include <stdio.h>
#include <stdlib.h>

// Если x <= 0, переменная r не инициализирована, и её чтение — UB.
__attribute__((noinline)) int f(int x){
    int r;
    if (x > 0) r = 10;
    return r;
}

// Для сравнения: то же самое, но БЕЗ UB — r инициализирована.
__attribute__((noinline)) int g(int x){
    int r = 0;
    if (x > 0) r = 10;
    return r;
}

int main(int argc, char **argv){
    int x = (argc > 1) ? atoi(argv[1]) : -5;    // отрицательный: ветка if НЕ должна сработать
    printf("вход x = %d  (ветка 'if (x > 0) r = 10;' выполниться НЕ должна)\n\n", x);
    printf("  без инициализации (UB) : f(%d) = %d\n", x, f(x));
    printf("  с инициализацией       : g(%d) = %d\n", x, g(x));
    puts("\n  -O0 -> f даёт 0  (со стека)");
    puts("  -O2 -> f даёт 10 (компилятор решил, что x>0 обязан быть истинным,");
    puts("                    и выбросил проверку вместе со вторым исходом)");
    return 0;
}
